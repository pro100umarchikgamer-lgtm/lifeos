"""Ordinary import hides advanced mapping and presents date ambiguity in place."""
from pathlib import Path
import os
from playwright.sync_api import sync_playwright, expect
from tool.check_web_platform import fixture, login


def main():
    out=Path('web_evidence/import-simple');out.mkdir(parents=True,exist_ok=True)
    with fixture() as (origin,backend,actor,workspace),sync_playwright() as p:
        browser=p.chromium.launch(**({'executable_path':os.environ['ULADIM_CHROMIUM']} if os.environ.get('ULADIM_CHROMIUM') else {}))
        page=browser.new_page(viewport={'width':1180,'height':900},locale='ru-RU')
        errors=[];page.on('pageerror',lambda error:errors.append(str(error)))
        login(page,origin)
        page.evaluate('importStatement()')
        d=page.get_by_role('dialog')
        file=d.locator('input[type=file]')
        file.set_input_files({'name':'clear.csv','mimeType':'text/csv','buffer':b'Date;Amount;Description\n2026-11-12;-2.25;Clear date'})
        expect(d.locator('tbody tr')).to_have_count(1)
        expect(d.locator('details[open]')).to_have_count(0)
        expect(d.locator('.statement-date-help')).to_be_hidden()
        expect(d.locator('select[name=encoding]')).to_be_hidden()
        expect(d.get_by_role('button',name='Импортировать выбранное',exact=True)).to_be_enabled()
        page.screenshot(path=str(out/'ordinary-desktop.png'),full_page=True)
        # Same export shape as the owner's recording, with synthetic values only.
        file.set_input_files({'name':'timestamp-export.csv','mimeType':'text/csv','buffer':b'transaction_id;transaction_datetime;posting_datetime;amount;currency;card_amount;description\nsynthetic-1;2026-11-10 19:00:00;2026-11-11 03:56:00;-50.00;RUB;-500.00;Synthetic purchase'})
        expect(d.locator('tbody tr')).to_have_count(1)
        expect(d.locator('tbody')).to_contain_text('2026-11-10')
        expect(d.locator('details[open]')).to_have_count(0)
        expect(d.locator('.statement-recognition-help')).to_be_hidden()
        expect(d.get_by_role('button',name='Импортировать выбранное',exact=True)).to_be_enabled()
        page.screenshot(path=str(out/'timestamp-export-automatic.png'),full_page=True)
        d.get_by_role('button',name='Импортировать выбранное',exact=True).click()
        expect(d.locator('.statement-receipt')).to_be_visible()
        expect(d.locator('.statement-receipt')).to_contain_text('Сохранено операций · 1')
        # A genuinely unknown column needs one shared choice, without an expert form.
        file.set_input_files({'name':'unknown-date.csv','mimeType':'text/csv','buffer':b'When booked;Amount;Description\n2026-11-12;-2.25;Unknown header'})
        expect(d.locator('.statement-required-fields select')).to_have_count(1)
        expect(d.locator('details[open]')).to_have_count(0)
        expect(d.locator('select[name=date]')).to_be_hidden()
        page.set_viewport_size({'width':375,'height':812})
        page.screenshot(path=str(out/'unknown-header-single-choice-phone.png'),full_page=True)
        d.locator('select[name=required-date]').select_option('0')
        expect(d.locator('tbody tr')).to_have_count(1)
        expect(d.locator('.statement-recognition-help')).to_be_hidden()
        expect(d.get_by_role('button',name='Импортировать выбранное',exact=True)).to_be_enabled()
        file.set_input_files({'name':'ambiguous.csv','mimeType':'text/csv','buffer':b'Date;Amount;Description\n04/05/2026;-2.25;Date clarification'})
        expect(d.locator('tbody tr')).to_have_count(1)
        expect(d.locator('.statement-date-help')).to_be_visible()
        expect(d.locator('details[open]')).to_have_count(0)
        expect(d.locator('select[name=dateFormat]')).to_be_visible()
        expect(d.locator('select[name=date]')).to_be_hidden()
        page.set_viewport_size({'width':375,'height':812})
        page.screenshot(path=str(out/'date-clarification-phone.png'),full_page=True)
        d.locator('select[name=dateFormat]').select_option('dmy')
        expect(d.get_by_role('button',name='Импортировать выбранное',exact=True)).to_be_enabled()
        expect(d.locator('tbody')).to_contain_text('2026-05-04')
        page.set_viewport_size({'width':375,'height':812})
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        page.screenshot(path=str(out/'date-choice-phone.png'),full_page=True)
        d.get_by_text('Исправить распознавание',exact=True).click()
        expect(d.locator('select[name=date]')).to_be_visible()
        file.set_input_files({'name':'invalid-date.csv','mimeType':'text/csv','buffer':b'Date;Amount;Description\ninvalid;-2.25;Correct in place'})
        d.get_by_role('button',name='Исправить строку',exact=True).click()
        correction=d.locator('.statement-row-correction')
        expect(correction).to_be_visible()
        expect(page.locator('dialog[open]')).to_have_count(1)
        page.screenshot(path=str(out/'inline-row-correction-phone.png'),full_page=True)
        correction.locator('input[name=date]').fill('2026-11-12')
        correction.get_by_role('button',name='Сохранить',exact=True).click()
        expect(correction).to_be_hidden()
        expect(d.locator('tbody')).to_contain_text('2026-11-12')
        expect(d.get_by_role('button',name='Импортировать выбранное',exact=True)).to_be_enabled()
        d.get_by_role('button',name='Импортировать выбранное',exact=True).click()
        expect(d.locator('.statement-receipt')).to_be_visible()
        expect(d.locator('.statement-receipt')).to_contain_text('Сохранено операций · 1')
        transactions=[row['data'] for row in backend.pull(actor,workspace,0)['records'] if row['kind']=='transaction']
        assert any(row['label']=='Synthetic purchase' and row['amount_minor']==5000 and row['date']=='2026-11-10' for row in transactions)
        assert any(row['label']=='Correct in place' and row['amount_minor']==225 and row['date']=='2026-11-12' for row in transactions)
        assert not errors,errors
        browser.close()
    print('PASS: bank timestamp export recognized; unknown header needs one shared choice; advanced stays folded; ambiguous dates remain explicit; row correction stays inline')

if __name__=='__main__':main()
