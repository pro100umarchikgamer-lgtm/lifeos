'use strict';
const assert = require('node:assert/strict');
require('../backend/webassets/app/money.js');
require('../backend/webassets/app/statement-formats.js');
const {read,table,sourceAccounts,preview}=globalThis.ULADIMStatement;
const csv = content=>read(new TextEncoder().encode(content));
const get = content=>sourceAccounts(csv(content));
assert.deepEqual(get('Date;Amount;account_id\n2026-11-11;1;owner-12345'),{2:{id:'owner-12345',provider:''}});
assert.deepEqual(get('Date;Amount;counterparty_account_number;Description\n2026-11-11;1;other-12345;IBAN owner-11111'),{});
assert.deepEqual(get('Date;Amount;Account ID;IBAN\n2026-11-11;1;owner-a;GB82 WEST 1234 5698 7654 32'),{});
assert.deepEqual(get('Date;Amount;IBAN\n2026-11-11;1;gb82 WEST 1234 5698 7654 32'),{2:{id:'GB82WEST12345698765432',provider:''}});
assert.deepEqual(get('Date;Amount;account_number\n2026-11-11;1;****1234'),{});
assert.deepEqual(get('Date;Amount;account_number\n2026-11-11;1;XXXX1234'),{});
assert.deepEqual(get('Date;Amount;account_number;bank_id\n2026-11-11;1; 0012345 ;bank-one'),{2:{id:'0012345',provider:'bank-one'}});
assert.deepEqual(get('Date;Amount;account_id\n2026-11-11;1;ab12owner'),{2:{id:'ab12owner',provider:''}});
assert.deepEqual(get('Date;Amount;account_id;bank_id;bank_code\n2026-11-11;1;owner-one;bank-one;bank-two'),{});
const json=csv(JSON.stringify({bank_id:'envelope-bank',account:{IBAN:'GB82 WEST 1234 5698 7654 32'},transactions:[{date:'2026-11-11',amount:'-1',currency:'USD',creditorAccount:{IBAN:'not-owner'}}]}));
assert.deepEqual(sourceAccounts(json)[2],{id:'GB82WEST12345698765432',provider:'envelope-bank'});
const jsonEntries=csv(JSON.stringify([{date:'2026-11-11',amount:'-1',accountId:'owner-1'},{date:'2026-11-12',amount:'2',account_number:'owner-2'}]));
// Two competing owner fields across a table are deliberately not guessed.
assert.deepEqual(sourceAccounts(jsonEntries),{});
const xlsx=table([['Date','Amount','AcctId'],['2026-11-11','-1','owner-xlsx']],'XLSX');
assert.equal(sourceAccounts(xlsx)[2].id,'owner-xlsx');
assert.deepEqual(sourceAccounts({...xlsx,format:'PDF'}),{});
const ofx='<OFX>'+['one','two'].map((id,i)=>`<STMTRS><CURDEF>USD<BANKACCTFROM><BANKID>bank-${i}<ACCTID>owner-${id}</BANKACCTFROM><BANKTRANLIST><STMTTRN><DTPOSTED>20261111<TRNAMT>-1<FITID>${i}<NAME>Sample</STMTTRN></BANKTRANLIST></STMTRS>`).join('')+'</OFX>';
const parsed=csv(ofx);
assert.deepEqual(sourceAccounts(parsed),{2:{id:'owner-one',provider:'bank-0'},3:{id:'owner-two',provider:'bank-1'}});
assert.equal(preview(parsed,{...parsed.detection,defaultCurrency:'USD'}).length,2);
assert.deepEqual(get('OFXHEADER:100\n<OFX><CURDEF>USD<BANKTRANLIST><STMTTRN><DTPOSTED>20261111<TRNAMT>-1<ACCTID>counterparty</STMTTRN></BANKTRANLIST></OFX>'),{});
console.log('Statement owner metadata: focused checks passed');
